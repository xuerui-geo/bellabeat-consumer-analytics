"""Run every SQL file in sql/ against the raw Fitbit CSVs (DuckDB), save results and charts.

Usage:  python src/run_analysis.py
Output: data/processed/*.csv (one per query), results.md (all query outputs), images/*.png
"""
from pathlib import Path

import duckdb
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "data" / "processed"
IMG = ROOT / "images"
OUT.mkdir(parents=True, exist_ok=True)
IMG.mkdir(exist_ok=True)

con = duckdb.connect()

# Raw views with parsed dates (Fitbit exports use M/D/YYYY and 12-hour timestamps)
con.execute(f"""
CREATE VIEW raw_daily_activity AS
SELECT *, strptime(ActivityDate, '%m/%d/%Y')::DATE AS activity_date
FROM read_csv_auto('{RAW / 'dailyActivity_merged.csv'}', types={{'ActivityDate': 'VARCHAR'}});

CREATE VIEW raw_sleep_day AS
SELECT *, strptime(SleepDay, '%m/%d/%Y %I:%M:%S %p')::DATE AS sleep_date
FROM read_csv_auto('{RAW / 'sleepDay_merged.csv'}', types={{'SleepDay': 'VARCHAR'}});

CREATE VIEW raw_hourly_steps AS
SELECT *, strptime(ActivityHour, '%m/%d/%Y %I:%M:%S %p') AS activity_hour
FROM read_csv_auto('{RAW / 'hourlySteps_merged.csv'}', types={{'ActivityHour': 'VARCHAR'}});

CREATE VIEW raw_weight_log AS
SELECT * FROM read_csv_auto('{RAW / 'weightLogInfo_merged.csv'}');
""")

# ---------------------------------------------------------------- run SQL files
report = ["# Query results\n", "Generated by `python src/run_analysis.py`.\n"]
results = {}
for sql_file in sorted((ROOT / "sql").glob("*.sql")):
    statements = [s.strip() for s in sql_file.read_text().split(";") if s.strip()]
    report.append(f"\n## {sql_file.name}\n")
    n = 0
    for stmt in statements:
        body = "\n".join(l for l in stmt.splitlines() if not l.strip().startswith("--")).strip()
        if not body:
            continue
        rel = con.sql(stmt)
        if rel is None:  # CREATE statements
            continue
        if list(rel.columns) == ["Count"]:  # row count echoed by CREATE TABLE AS
            continue
        n += 1
        df = rel.df()
        key = f"{sql_file.stem}_{n}"
        results[key] = df
        df.to_csv(OUT / f"{key}.csv", index=False)
        report.append(f"\n**{key}**\n\n{df.to_markdown(index=False)}\n")
(ROOT / "results.md").write_text("\n".join(report))

# ---------------------------------------------------------------- charts
plt.rcParams.update({"figure.dpi": 150, "axes.spines.top": False, "axes.spines.right": False,
                     "font.size": 10})
PINK, GREY, DARK = "#E36F8E", "#B9B9B9", "#333333"
daily = con.sql("SELECT * FROM daily").df()

# 1. Steps vs calories
fig, ax = plt.subplots(figsize=(7, 4.2))
ax.scatter(daily["steps"], daily["calories"], s=10, alpha=.35, color=PINK, edgecolor="none")
ax.set_xlabel("Daily steps"); ax.set_ylabel("Calories burned")
ax.set_title("More steps, more calories burned", loc="left", fontweight="bold")
fig.tight_layout(); fig.savefig(IMG / "01_steps_vs_calories.png"); plt.close(fig)

# 2. Calories by step band
band = results["03_activity_vs_calories_2"]
fig, ax = plt.subplots(figsize=(7, 3.8))
ax.bar(band["step_band"].str[4:], band["avg_calories"], color=[GREY, GREY, PINK, PINK])
for i, v in enumerate(band["avg_calories"]):
    ax.text(i, v + 30, f"{v:,.0f}", ha="center")
ax.set_ylabel("Avg calories / day"); ax.set_xlabel("Daily steps")
ax.set_title("Calories burned by daily step band", loc="left", fontweight="bold")
fig.tight_layout(); fig.savefig(IMG / "02_calories_by_step_band.png"); plt.close(fig)

# 3. Sleep by sedentary share of awake time
sb = results["04_sedentary_vs_sleep_3"]
fig, ax = plt.subplots(figsize=(7, 3.8))
ax.bar(sb["sedentary_share_band"].str[4:], sb["pct_7h_plus"], color=[PINK, GREY, GREY, GREY])
for i, (v, n) in enumerate(zip(sb["pct_7h_plus"], sb["user_days"])):
    ax.text(i, v + 1.5, f"{v:.0f}%", ha="center")
    ax.text(i, 3, f"n={n}", ha="center", color="white", fontsize=8)
ax.set_ylim(0, 100); ax.set_ylabel("% of nights with 7h+ sleep")
ax.set_xlabel("Sedentary share of awake time that day")
ax.set_title("Only the least sedentary days stand out for sleep", loc="left", fontweight="bold")
fig.tight_layout(); fig.savefig(IMG / "03_sleep_by_sedentary_share.png"); plt.close(fig)

# 4. Steps by hour
hr = results["05_usage_patterns_3"]
fig, ax = plt.subplots(figsize=(7, 3.6))
colors = [PINK if h in (12, 13, 17, 18, 19) else GREY for h in hr["hour_of_day"]]
ax.bar(hr["hour_of_day"], hr["avg_steps"], color=colors)
ax.set_xticks(range(0, 24, 2)); ax.set_xlabel("Hour of day"); ax.set_ylabel("Avg steps")
ax.set_title("Activity peaks at lunch and after work", loc="left", fontweight="bold")
fig.tight_layout(); fig.savefig(IMG / "04_steps_by_hour.png"); plt.close(fig)

# 5. Engagement
eng = con.sql("SELECT * FROM user_engagement ORDER BY days_worn").df()
fig, ax = plt.subplots(figsize=(7, 3.8))
x = range(len(eng))
ax.bar(x, eng["days_worn"], color=GREY, label="Days tracker worn")
ax.bar(x, eng["nights_sleep_logged"], color=PINK, label="Nights sleep logged")
ax.set_xticks([]); ax.set_xlabel("Users (sorted by days worn)"); ax.set_ylabel("Days (of 31)")
ax.legend(frameon=False, loc="upper left")
ax.set_title("Most users wear the tracker daily, far fewer track sleep", loc="left", fontweight="bold")
fig.tight_layout(); fig.savefig(IMG / "05_engagement.png"); plt.close(fig)

print("Done:", len(results), "query outputs,", len(list(IMG.glob('*.png'))), "charts")
